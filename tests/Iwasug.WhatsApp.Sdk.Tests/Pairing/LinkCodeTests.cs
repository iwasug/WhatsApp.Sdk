    private sealed record KatFixture(
        [property: JsonPropertyName("provenance")] string Provenance,
        [property: JsonPropertyName("pbkdf2")] Pbkdf2Vector Pbkdf2,
        [property: JsonPropertyName("ctr")] CtrVector Ctr,
        [property: JsonPropertyName("hkdfAdv")] HkdfVector HkdfAdv,
        [property: JsonPropertyName("hkdfBundle")] HkdfVector HkdfBundle,
        [property: JsonPropertyName("gcm")] GcmVector Gcm,
        [property: JsonPropertyName("chain")] ChainVector Chain);

    private static KatFixture LoadFixture()
    {
        string path = Path.Combine(AppContext.BaseDirectory, "TestData", "link-code-kats.json");
        string json = File.ReadAllText(path);
        return JsonSerializer.Deserialize<KatFixture>(json)
            ?? throw new InvalidOperationException("Link-code KAT fixture failed to deserialize.");
    }

    private static byte[] FromHex(string hex) => Convert.FromHexString(hex);

    private static string Hex(byte[] bytes) => Convert.ToHexString(bytes).ToLowerInvariant();

    private static byte[] FixedBytes(int start, int length = 32)
    {
        byte[] bytes = new byte[length];
        for (int i = 0; i < bytes.Length; i++)
        {
            bytes[i] = (byte)(start + i);
        }

        return bytes;
    }

    [Fact]
    public void Generate_produces_eight_crockford_characters_displayed_hyphenated()
    {
        PairingCodeGenerator.Alphabet.Should().Be(
            Alphabet, "the alphabet is the single declared source — I, O, U stay excluded");

        string raw = PairingCodeGenerator.GenerateCode(_ => FixedBytes(0x11, 5));
        raw.Should().HaveLength(8, "five bytes carry exactly 40 bits = eight 5-bit characters");
        foreach (char c in raw)
        {
            Alphabet.Contains(c).Should().BeTrue($"every character is drawn from the Crockford alphabet, found '{c}'");
        }

        string display = PairingCodeGenerator.ToDisplay(raw);
        display.Should().HaveLength(9, "eight characters plus one hyphen");
        display[4].Should().Be('-', "the hyphen sits at index 4: XXXX-XXXX");
        display.Should().Be(raw[..4] + "-" + raw[4..]);
    }

    [Fact]
    public void Same_bytes_always_produce_same_code()
    {
        byte[] input = FixedBytes(0x22, 5);
        string first = PairingCodeGenerator.GenerateCode(_ => (byte[])input.Clone());
        string second = PairingCodeGenerator.GenerateCode(_ => (byte[])input.Clone());
        first.Should().Be(second, "the mapping is pure — inject the randomness, not the mapping");
    }

    [Fact]
    public void Boundary_bytes_map_to_documented_worked_examples()
    {
        PairingCodeGenerator.GenerateCode(_ => new byte[5]).Should().Be(
            "11111111", "all-zero bits index the alphabet's first symbol eight times");
        PairingCodeGenerator.GenerateCode(_ => new byte[] { 0xFF, 0xFF, 0xFF, 0xFF, 0xFF }).Should().Be(
            "ZZZZZZZZ", "all-one bits index the alphabet's last symbol eight times");
        PairingCodeGenerator.ToDisplay("11111111").Should().Be("1111-1111");
    }

