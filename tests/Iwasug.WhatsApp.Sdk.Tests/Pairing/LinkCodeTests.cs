    [Fact]
    public void DeriveKey_matches_pbkdf2_kat_and_dual_api_agreement()
    {
        KatFixture fixture = LoadFixture();
        fixture.Pbkdf2.Iterations.Should().Be(
            LinkCodeCrypto.Pbkdf2Iterations, "the fixture pins the named iteration constant");
        fixture.Pbkdf2.Iterations.Should().Be(131072);

        byte[] key = LinkCodeCrypto.DeriveKey(
            Encoding.ASCII.GetBytes(fixture.Pbkdf2.PasswordAscii),
            FromHex(fixture.Pbkdf2.SaltHex));
        Hex(key).Should().Be(fixture.Pbkdf2.KeyHex);

        Hex(ManualPbkdf2Sha256(
                Encoding.ASCII.GetBytes(fixture.Pbkdf2.PasswordAscii),
                FromHex(fixture.Pbkdf2.SaltHex),
                fixture.Pbkdf2.Iterations,
                fixture.Pbkdf2.OutputLength)).Should().Be(
            fixture.Pbkdf2.KeyHex, "an independent RFC 8018 recomputation agrees — not one call path");
    }

    /// <summary>
    /// Test-only RFC 8018 §5.2 recomputation (HMAC-SHA256 PRF, big-endian block
    /// index, XOR accumulation): the independent check behind the PBKDF2 KAT.
    /// Never shipped — production uses the BCL.
    /// </summary>
    private static byte[] ManualPbkdf2Sha256(byte[] password, byte[] salt, int iterations, int outputLength)
    {
        using var prf = new HMACSHA256(password);
        byte[] output = new byte[outputLength];
        byte[] block = new byte[salt.Length + 4];
        salt.CopyTo(block, 0);
        int written = 0;
        for (uint index = 1; written < outputLength; index++)
        {
            block[salt.Length] = (byte)(index >> 24);
            block[salt.Length + 1] = (byte)(index >> 16);
            block[salt.Length + 2] = (byte)(index >> 8);
            block[salt.Length + 3] = (byte)index;
            byte[] u = prf.ComputeHash(block);
            byte[] acc = (byte[])u.Clone();
            for (int round = 1; round < iterations; round++)
            {
                u = prf.ComputeHash(u);
                for (int i = 0; i < acc.Length; i++)
                {
                    acc[i] ^= u[i];
                }
            }

            int take = Math.Min(acc.Length, outputLength - written);
            Array.Copy(acc, 0, output, written, take);
            written += take;
            CryptographicOperations.ZeroMemory(acc);
            CryptographicOperations.ZeroMemory(u);
        }

        return output;
    }

    [Fact]
    public void Ctr_encrypt_matches_kat_and_decrypt_round_trips()
    {
        KatFixture fixture = LoadFixture();
        byte[] key = FromHex(fixture.Ctr.KeyHex);
        byte[] iv = FromHex(fixture.Ctr.IvHex);
        byte[] plaintext = FromHex(fixture.Ctr.PlaintextHex);

        Hex(LinkCodeCrypto.EncryptCtr(key, iv, plaintext)).Should().Be(fixture.Ctr.CiphertextHex);
        LinkCodeCrypto.DecryptCtr(key, iv, FromHex(fixture.Ctr.CiphertextHex)).Should().Equal(
            plaintext, "CTR decryption inverts encryption — the composition is sound");
    }

    [Fact]
    public void DeriveAdvSecret_matches_hkdf_kat()
    {
        KatFixture fixture = LoadFixture();
        fixture.HkdfAdv.Info.Should().Be("adv_secret");
        byte[] okm = LinkCodeCrypto.DeriveAdvSecret(
            FromHex(fixture.HkdfAdv.IkmHex),
            FromHex(fixture.HkdfAdv.SaltHex),
            Encoding.ASCII.GetBytes(fixture.HkdfAdv.Info));
        okm.Should().HaveCount(32, "the adv secret is 32 bytes");
        Hex(okm).Should().Be(fixture.HkdfAdv.OkmHex);
    }

    [Fact]
    public void DeriveBundleKey_matches_hkdf_kat()
    {
        KatFixture fixture = LoadFixture();
        byte[] bundleKey = LinkCodeCrypto.DeriveBundleKey(
            FromHex(fixture.HkdfBundle.IkmHex),
            FromHex(fixture.HkdfBundle.SaltHex));
        bundleKey.Should().HaveCount(32, "the bundle key is 32 bytes");
        Hex(bundleKey).Should().Be(fixture.HkdfBundle.OkmHex);
    }

    [Fact]
    public void Gcm_bundle_matches_kat_and_tampering_throws()
    {
        KatFixture fixture = LoadFixture();
        byte[] key = FromHex(fixture.Gcm.KeyHex);
        byte[] nonce = FromHex(fixture.Gcm.NonceHex);
        byte[] plaintext = FromHex(fixture.Gcm.PlaintextHex);

        Hex(LinkCodeCrypto.ProtectBundle(key, nonce, plaintext)).Should().Be(
            fixture.Gcm.BundleHex, "same key/nonce/plaintext seals deterministically");
        LinkCodeCrypto.UnprotectBundle(key, FromHex(fixture.Gcm.BundleHex)).Should().Equal(
            plaintext, "the sealed bundle opens under its own key");

        byte[] tampered = FromHex(fixture.Gcm.BundleHex);
        tampered[tampered.Length - 1] ^= 0xFF;
        Action open = () => LinkCodeCrypto.UnprotectBundle(key, tampered);
        open.Should().Throw<CryptographicException>(
            "GCM integrity is behavioral — a flipped byte fails authentication, never silent plaintext");
    }

    [Fact]
    public void Chain_end_to_end_recomputes_all_stages_to_one_fixture_value()
    {
        KatFixture fixture = LoadFixture();
        ChainVector chain = fixture.Chain;

        byte[] linkKey = LinkCodeCrypto.DeriveKey(
            Encoding.ASCII.GetBytes(chain.Code), FromHex(chain.SaltHex));
        byte[] bundleKey = LinkCodeCrypto.DeriveBundleKey(linkKey, FromHex(chain.SaltHex));
        byte[] bundle = LinkCodeCrypto.ProtectBundle(
            bundleKey, FromHex(chain.NonceHex), FromHex(chain.PlaintextHex));
        Hex(bundle).Should().Be(
            chain.BundleHex, "one fixture value covers the whole derivation — any stage's parameter change breaks it");

        LinkCodeCrypto.UnprotectBundle(bundleKey, bundle).Should().Equal(
            FromHex(chain.PlaintextHex), "the chained bundle opens end to end");
    }

    [Fact]
    public void WrapEphemeral_keeps_salt_iv_layout_and_unwraps()
    {
        byte[] salt = FixedBytes(0x00);
        byte[] iv = FixedBytes(0x40, 16);
        byte[] ephemeral = FixedBytes(0x60);
        byte[] linkKey = LinkCodeCrypto.DeriveKey(Encoding.ASCII.GetBytes("K7M2QX9D"), salt);

        byte[] wrapped = LinkCodeCrypto.WrapEphemeral(linkKey, salt, iv, ephemeral);
        wrapped.Should().HaveCount(
            LinkCodeCrypto.WrappedEphemeralSize, "the wrap is exactly salt(32) + iv(16) + ct(32)");
        wrapped.AsSpan(0, 32).ToArray().Should().Equal(salt, "the salt rides in the clear");
        wrapped.AsSpan(32, 16).ToArray().Should().Equal(iv, "the IV rides in the clear");
        LinkCodeCrypto.UnwrapEphemeral(linkKey, wrapped).Should().Equal(
            ephemeral, "the wrapped ephemeral recovers under its own link key");
    }
}
