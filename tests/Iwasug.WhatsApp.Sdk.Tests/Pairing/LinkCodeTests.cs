/// <summary>
/// Link-code proofs (03-05 Task 1, CONN-02, T-3-10): the 5-byte → 8-character
/// Crockford format with <c>XXXX-XXXX</c> display, the phone-number validation
/// contract, and every crypto stage KAT-pinned against
/// <c>link-code-kats.json</c> — any derivation parameter drift breaks CI
/// instead of breaking real pairings.
/// </summary>
/// <remarks>
/// <para>
/// Fixture provenance: every expected hex below is committed in
/// <c>TestData/link-code-kats.json</c> (self-generated by this repo's own
/// in-box derivations with fixed inputs; parameters pinned to 03-RESEARCH.md
/// Code Examples 2–3 — no upstream bytes). Cross-validation is behavioral:
/// CTR decrypt round-trips, GCM tampering throws, and the chained record
/// recomputes all four stages in sequence.
/// </para>
/// <para>
/// Output discipline (V6/T-3-10): assertions compare hex strings of public
/// fixture vectors — raw key bytes never enter an assertion message, so even
/// a failing run cannot print key material.
/// </para>
/// </remarks>
public sealed class LinkCodeTests
{
